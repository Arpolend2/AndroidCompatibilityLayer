#include "../network_snapshot.h"

#include <cassert>

int main()
{
    assert(auroraNetworkSnapshot(false, 0, 0, false) == ANDROID_COMPATIBILITY_LAYER_NETWORK_UNKNOWN);
    assert(auroraNetworkSnapshot(true, 0, 0, false) == ANDROID_COMPATIBILITY_LAYER_NETWORK_OFFLINE);
    assert(auroraNetworkSnapshot(true, 1, ANDROID_COMPATIBILITY_LAYER_NETWORK_TRANSPORT_WIFI, false) ==
           (ANDROID_COMPATIBILITY_LAYER_NETWORK_CONNECTED | ANDROID_COMPATIBILITY_LAYER_NETWORK_TRANSPORT_WIFI));
    assert(auroraNetworkSnapshot(true, 1, ANDROID_COMPATIBILITY_LAYER_NETWORK_TRANSPORT_CELLULAR, true) ==
           (ANDROID_COMPATIBILITY_LAYER_NETWORK_CONNECTED | ANDROID_COMPATIBILITY_LAYER_NETWORK_TRANSPORT_CELLULAR | ANDROID_COMPATIBILITY_LAYER_NETWORK_INTERNET));
    assert(auroraNetworkSnapshot(true, 2, ANDROID_COMPATIBILITY_LAYER_NETWORK_TRANSPORT_WIFI, true) ==
           (ANDROID_COMPATIBILITY_LAYER_NETWORK_CONNECTED | ANDROID_COMPATIBILITY_LAYER_NETWORK_INTERNET));
    assert(auroraNetworkSnapshot(false, 0, 0, true) ==
           (ANDROID_COMPATIBILITY_LAYER_NETWORK_CONNECTED | ANDROID_COMPATIBILITY_LAYER_NETWORK_INTERNET));

    const int wifi = ANDROID_COMPATIBILITY_LAYER_NETWORK_CONNECTED | ANDROID_COMPATIBILITY_LAYER_NETWORK_TRANSPORT_WIFI | ANDROID_COMPATIBILITY_LAYER_NETWORK_INTERNET;
    assert(auroraNetworkCapabilities(wifi, true, true, ANDROID_COMPATIBILITY_LAYER_NETWORK_TRANSPORT_WIFI, true, true) ==
           (wifi | ANDROID_COMPATIBILITY_LAYER_NETWORK_VALIDATED | ANDROID_COMPATIBILITY_LAYER_NETWORK_TRUSTED));
    assert(auroraNetworkCapabilities(wifi, true, true, ANDROID_COMPATIBILITY_LAYER_NETWORK_TRANSPORT_WIFI, false, true) ==
           (wifi | ANDROID_COMPATIBILITY_LAYER_NETWORK_VALIDATED | ANDROID_COMPATIBILITY_LAYER_NETWORK_TRUSTED));
    assert(auroraNetworkCapabilities(ANDROID_COMPATIBILITY_LAYER_NETWORK_CONNECTED | ANDROID_COMPATIBILITY_LAYER_NETWORK_TRANSPORT_WIFI, true, true,
                                     ANDROID_COMPATIBILITY_LAYER_NETWORK_TRANSPORT_WIFI, true, true) ==
           (ANDROID_COMPATIBILITY_LAYER_NETWORK_CONNECTED | ANDROID_COMPATIBILITY_LAYER_NETWORK_TRANSPORT_WIFI | ANDROID_COMPATIBILITY_LAYER_NETWORK_TRUSTED));
    assert(auroraNetworkCapabilities(wifi, true, true, ANDROID_COMPATIBILITY_LAYER_NETWORK_TRANSPORT_WIFI, true, false) ==
           (wifi | ANDROID_COMPATIBILITY_LAYER_NETWORK_VALIDATED));
    assert(auroraNetworkCapabilities(wifi, false, true, ANDROID_COMPATIBILITY_LAYER_NETWORK_TRANSPORT_WIFI, true, true) == wifi);
    assert(auroraNetworkCapabilities(wifi, true, false, ANDROID_COMPATIBILITY_LAYER_NETWORK_TRANSPORT_WIFI, true, true) == wifi);
    assert(auroraNetworkCapabilities(wifi, true, true, ANDROID_COMPATIBILITY_LAYER_NETWORK_TRANSPORT_CELLULAR, true, true) == wifi);
    assert(auroraNetworkCapabilities(ANDROID_COMPATIBILITY_LAYER_NETWORK_OFFLINE, true, true, ANDROID_COMPATIBILITY_LAYER_NETWORK_TRANSPORT_WIFI, true, true) ==
           ANDROID_COMPATIBILITY_LAYER_NETWORK_OFFLINE);
}
